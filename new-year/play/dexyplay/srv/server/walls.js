/** progress = { walls: расписанных стен 1–6, mural: bool } → id достигнутых уровней */
function reached(p) {
  return TIERS.filter((t) => (t.mural ? Boolean(p.mural) : p.walls >= t.walls)).map((t) => t.id);
}

